//! Symbols Icon Theme resolver and asset management.
//!
//! Provides file and folder icon resolution based on the Symbols icon theme
//! (Miguel Solorio / Joan S. Garcia, MIT).

#[cfg(feature = "gui")]
use gpui::{AssetSource, Result, SharedString};
#[cfg(feature = "gui")]
use std::borrow::Cow;

#[cfg(feature = "gui")]
#[derive(rust_embed::RustEmbed)]
#[folder = "assets/symbols"]
#[include = "*.svg"]
#[include = "**/*.svg"]
pub struct SymbolsAssets;

#[cfg(feature = "gui")]
pub struct ChamberAssets;

#[cfg(feature = "gui")]
impl AssetSource for ChamberAssets {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {
        if path.is_empty() {
            return Ok(None);
        }
        let clean_path = path.strip_prefix("symbols/").unwrap_or(path);
        if let Some(f) = SymbolsAssets::get(clean_path) {
            return Ok(Some(f.data));
        }
        gpui_component_assets::Assets.load(path)
    }

    fn list(&self, path: &str) -> Result<Vec<SharedString>> {
        let mut items: Vec<SharedString> = SymbolsAssets::iter()
            .filter_map(|p| {
                let full = format!("symbols/{p}");
                if full.starts_with(path) || p.starts_with(path) {
                    Some(full.into())
                } else {
                    None
                }
            })
            .collect();
        if let Ok(comp_items) = gpui_component_assets::Assets.list(path) {
            items.extend(comp_items);
        }
        Ok(items)
    }
}

/// Resolve a file path or filename to its corresponding Symbols SVG asset path.
pub fn file_icon_path(path: &str) -> &'static str {
    let p = std::path::Path::new(path);
    let file_name = p.file_name().and_then(|f| f.to_str()).unwrap_or(path);
    let lower_name = file_name.to_ascii_lowercase();

    // Check exact filenames / stems first
    if let Some(icon) = match_file_stem(&lower_name) {
        return icon;
    }

    // Check compound / multi-part extensions (e.g. .tar.gz, .d.ts, .test.tsx)
    if let Some((_, compound_ext)) = lower_name.split_once('.') {
        if let Some(icon) = match_file_suffix(compound_ext) {
            return icon;
        }
    }

    // Check standard single extension
    if let Some(ext) = p.extension().and_then(|e| e.to_str()) {
        let lower_ext = ext.to_ascii_lowercase();
        if let Some(icon) = match_file_suffix(&lower_ext) {
            return icon;
        }
    }

    // Default file icon
    "symbols/files/document.svg"
}

/// Resolve a folder name and expansion state to its corresponding Symbols SVG asset path.
pub fn folder_icon_path(folder_name: &str, is_expanded: bool) -> &'static str {
    let clean = folder_name.trim_matches(|c| c == '/' || c == '\\');
    let lower = clean.to_ascii_lowercase();

    if let Some((collapsed, expanded)) = match_folder(&lower) {
        if is_expanded {
            expanded
        } else {
            collapsed
        }
    } else if is_expanded {
        "symbols/folders/folder-open.svg"
    } else {
        "symbols/folders/folder.svg"
    }
}

