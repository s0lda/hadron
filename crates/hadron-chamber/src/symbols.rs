#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_file_icon_path_resolutions() {
        assert_eq!(file_icon_path("src/main.rs"), "symbols/files/rust.svg");
        assert_eq!(file_icon_path("Cargo.toml"), "symbols/files/gear.svg");
        assert_eq!(file_icon_path("Cargo.lock"), "symbols/files/lock.svg");
        assert_eq!(file_icon_path("package.json"), "symbols/files/node.svg");
        assert_eq!(file_icon_path("tsconfig.json"), "symbols/files/tsconfig.svg");
        assert_eq!(file_icon_path("index.ts"), "symbols/files/ts.svg");
        assert_eq!(file_icon_path("App.tsx"), "symbols/files/react-ts.svg");
        assert_eq!(file_icon_path("script.py"), "symbols/files/python.svg");
        assert_eq!(file_icon_path("main.go"), "symbols/files/go.svg");
        assert_eq!(file_icon_path("README.md"), "symbols/files/markdown.svg");
        assert_eq!(file_icon_path(".gitignore"), "symbols/files/git.svg");
        assert_eq!(file_icon_path("Dockerfile"), "symbols/files/docker.svg");
        assert_eq!(file_icon_path("styles.scss"), "symbols/files/sass.svg");
        assert_eq!(file_icon_path("database.sql"), "symbols/files/database.svg");
        assert_eq!(file_icon_path("archive.tar.gz"), "symbols/files/compressed.svg");
        assert_eq!(file_icon_path("unknown_file.xyz_unknown"), "symbols/files/document.svg");
    }

    #[test]
    fn test_folder_icon_path_resolutions() {
        assert_eq!(folder_icon_path("src", false), "symbols/folders/folder-orange-code.svg");
        assert_eq!(folder_icon_path("src", true), "symbols/folders/folder-orange-code.svg");
        assert_eq!(folder_icon_path("docs", false), "symbols/folders/folder-documents.svg");
        assert_eq!(folder_icon_path("docs", true), "symbols/folders/folder-documents.svg");
        assert_eq!(folder_icon_path(".github", false), "symbols/folders/folder-github.svg");
        assert_eq!(folder_icon_path(".git", false), "symbols/folders/folder-red.svg");
        assert_eq!(folder_icon_path("some_custom_folder", false), "symbols/folders/folder.svg");
        assert_eq!(folder_icon_path("some_custom_folder", true), "symbols/folders/folder-open.svg");
    }

    #[cfg(feature = "gui")]
    #[test]
    fn test_chamber_assets_load_symbols() {
        let assets = ChamberAssets;
        let rust_svg = assets.load("symbols/files/rust.svg").expect("load should succeed");
        assert!(rust_svg.is_some(), "rust.svg should exist in embedded assets");
        let folder_svg = assets.load("symbols/folders/folder.svg").expect("load should succeed");
        assert!(folder_svg.is_some(), "folder.svg should exist in embedded assets");
    }
}
